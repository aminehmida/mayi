#!/usr/bin/env python3
"""Publishes the release built by scripts/release.sh and points Homebrew at it.

    scripts/publish.py            uses the version in Cargo.toml

1. Creates the GitHub release vVERSION on aminehmida/mayi (a pre-release if the
   version has a suffix such as -alpha.1), with dist/VERSION/* attached and
   docs/releases/vVERSION.md as its notes. The tag must already be pushed.
2. Rewrites Formula/mayi-cli.rb and Casks/mayi.rb with the new files' asset ids
   and checksums. Commit and push those afterwards: the tap reads the default
   branch.

The repository is private, so Homebrew downloads through the GitHub API with
a token: HOMEBREW_GITHUB_API_TOKEN, or else `gh auth token --user aminehmida`.
This script uses the same token, through gh.
"""

import hashlib
import json
import os
import pathlib
import re
import subprocess
import sys

REPO = "aminehmida/mayi"
OWNER = REPO.split("/")[0]
ROOT = pathlib.Path(__file__).resolve().parent.parent


def gh(*args, capture=True):
    env = dict(os.environ)
    if "GH_TOKEN" not in env:
        env["GH_TOKEN"] = subprocess.run(
            ["gh", "auth", "token", "--user", OWNER], capture_output=True, text=True, check=True
        ).stdout.strip()
    result = subprocess.run(["gh", *args], capture_output=capture, text=True, env=env, cwd=ROOT)
    if result.returncode != 0:
        sys.exit(f"gh {' '.join(args[:3])} failed: {result.stderr if capture else ''}")
    return result.stdout if capture else ""


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


# Both files compute the token the same way: the variable Homebrew keeps
# unmasked during evaluation, or else the owner's token from the GitHub CLI.
TOKEN_RUBY = f'''  # The release files are in a private repository, so they are fetched
  # through the GitHub API with a token that can read it.
  # Homebrew runs this with a reduced PATH, so gh is looked up in the
  # caller's own.
  token = ENV.fetch("HOMEBREW_GITHUB_API_TOKEN", "").strip
  if token.empty? && (gh = which("gh", ORIGINAL_PATHS))
    token = ::Utils.popen_read(gh.to_s, "auth", "token", "--user", "{OWNER}").strip
  end
  headers = ["Accept: application/octet-stream", "Authorization: Bearer #{{token}}"]
'''


def api_url(asset):
    return f"https://api.github.com/repos/{REPO}/releases/assets/{asset['id']}"


def formula(version, assets, sums):
    def block(target, indent):
        name = f"mayi-{version}-{target}.tar.gz"
        return f'{indent}url "{api_url(assets[name])}", headers: headers\n{indent}sha256 "{sums[name]}"'

    return f'''# Generated by scripts/publish.py for {version}.
class MayiCli < Formula
  desc "Use secrets and website logins in commands without seeing them"
  homepage "https://github.com/{REPO}"
  version "{version}"

{TOKEN_RUBY}
  on_macos do
    depends_on arch: :arm64
{block("aarch64-apple-darwin", "    ")}
  end
  on_linux do
    on_intel do
{block("x86_64-unknown-linux-musl", "      ")}
    end
    on_arm do
{block("aarch64-unknown-linux-musl", "      ")}
    end
  end

  def install
    bin.install "mayi"
    pkgshare.install "skill"
  end

  def caveats
    <<~EOS
      This is the requester only. It asks a vault device (the Mayi app on a Mac
      or an Android phone) for secrets; pair it with `mayi pair TOKEN`.

      The agent skill is in #{{opt_pkgshare}}/skill/mayi. For Claude Code:
        cp -R #{{opt_pkgshare}}/skill/mayi ~/.claude/skills/
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/mayi --version")
  end
end
'''


def cask(version, assets, sums):
    name = f"Mayi-{version}-macos-arm64.zip"
    return f'''# Generated by scripts/publish.py for {version}.
cask "mayi" do
{TOKEN_RUBY}
  version "{version}"
  sha256 "{sums[name]}"

  url "{api_url(assets[name])}", header: headers
  name "Mayi"
  desc "Approve, on your own devices, the secrets and logins AI agents ask for"
  homepage "https://github.com/{REPO}"

  depends_on arch: :arm64
  depends_on macos: ">= :sonoma"

  app "Mayi.app"
  binary "#{{appdir}}/Mayi.app/Contents/Resources/mayi"

  # The app is signed ad hoc, not by an Apple developer account, so macOS
  # would refuse to open a downloaded copy. It is your own build.
  postflight do
    system_command "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "#{{appdir}}/Mayi.app"]
  end

  caveats <<~EOS
    Mayi keeps its vault in ~/Library/Application Support/Mayi. Uninstalling
    the app leaves it there; delete it yourself only if you mean to lose the
    secrets in it.

    The agent skill is inside the app:
      cp -R #{{appdir}}/Mayi.app/Contents/Resources/skill/mayi ~/.claude/skills/
  EOS
end
'''


def main():
    cargo = (ROOT / "Cargo.toml").read_text()
    version = re.search(r'^version = "(.+)"$', cargo, re.M).group(1)
    tag = f"v{version}"
    dist = ROOT / "dist" / version
    notes = ROOT / "docs" / "releases" / f"{tag}.md"
    files = sorted(p for p in dist.iterdir() if p.is_file())
    if not files or not notes.exists():
        sys.exit(f"need {dist} (scripts/release.sh) and {notes}")

    existing = gh("release", "list", "-R", REPO, "--json", "tagName", "-q", ".[].tagName").split()
    if tag not in existing:
        args = ["release", "create", tag, "-R", REPO, "--verify-tag", "--title", f"Mayi {version}",
                "--notes-file", str(notes)]
        if "-" in version:
            args.append("--prerelease")
        gh(*args, *map(str, files), capture=False)

    release = json.loads(gh("api", f"repos/{REPO}/releases/tags/{tag}"))
    assets = {a["name"]: a for a in release["assets"]}
    sums = {p.name: sha256(p) for p in files}
    for name, digest in sums.items():
        remote = assets.get(name, {}).get("digest", "")
        if remote and remote != f"sha256:{digest}":
            sys.exit(f"{name} on GitHub does not match dist/: {remote}")

    (ROOT / "Formula").mkdir(exist_ok=True)
    (ROOT / "Casks").mkdir(exist_ok=True)
    (ROOT / "Formula" / "mayi-cli.rb").write_text(formula(version, assets, sums))
    (ROOT / "Casks" / "mayi.rb").write_text(cask(version, assets, sums))
    print(f"Released {tag}: {release['html_url']}")
    print("Wrote Formula/mayi-cli.rb and Casks/mayi.rb; commit and push them.")


if __name__ == "__main__":
    main()
